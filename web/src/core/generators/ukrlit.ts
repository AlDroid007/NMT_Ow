import { sample, shuffle } from '../py'
import { GEN_SOURCE, LABELS5, registerDrill } from './common'

registerDrill('lit_pseudonyms', () => {
  const pool: Array<[string, string]> = [
    ['Микола Хвильовий', 'Фітільов'],
    ['Іван Багряний', 'Лозов’ягін'],
    ['Остап Вишня', 'Губенко'],
    ['Іван Карпенко-Карий', 'Тобілевич'],
    ['Олександр Олесь', 'Кандиба'],
    ['Леся Українка', 'Косач'],
    ['Панас Мирний', 'Рудченко'],
    ['Марко Вовчок', 'Вілінська'],
  ]
  const picked = sample(pool, 5)
  const target = picked[0]
  const opts = shuffle(picked.map((s) => s[1]))
  const labels = [...LABELS5]
  const ci = opts.indexOf(target[1])
  return {
    subject: 'ukrlit',
    section: 'Література XX ст.',
    source: GEN_SOURCE,
    qtype: 'single',
    max_points: 1,
    prompt: `Яке справжнє прізвище має український письменник / письменниця ${target[0]}?`,
    options: opts,
    labels,
    answer: labels[ci],
    hint: 'Згадай пари «псевдонім — справжнє прізвище», які щороку трапляються на НМТ.',
    rule: 'Обов’язкові псевдоніми для НМТ: Хвильовий = Фітільов, Багряний = Лозов’ягін, Вишня = Губенко, Карпенко-Карий = Тобілевич, Олесь = Кандиба, Леся Українка = Косач, Панас Мирний = Рудченко.',
    solution: `Справжнє прізвище автора (${target[0]}) — ${target[1]} (${labels[ci]}).`,
    drill_key: 'lit_pseudonyms',
  }
})

