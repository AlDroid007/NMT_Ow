-- Start of a training. Limits and paid subjects will be checked here (with purchases);
-- for now every training is allowed. Repeating the call with the same id is harmless.
create or replace function public.begin_session(
    p_session_id uuid,
    p_profile_id uuid,
    p_subjects text[],
    p_length_mode text,
    p_tutor_mode boolean default true,
    p_mistake_drill boolean default false,
    p_focus_section text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    uid uuid := auth.uid();
    s public.sessions;
begin
    if uid is null then
        raise exception 'not signed in';
    end if;
    if not exists (select 1 from public.profiles where id = p_profile_id and owner = uid) then
        raise exception 'profile not found';
    end if;
    select * into s from public.sessions where id = p_session_id;
    if found then
        if s.owner <> uid then
            raise exception 'not allowed';
        end if;
        return jsonb_build_object('allowed', true, 'session_id', s.id, 'started_at', s.started_at);
    end if;
    insert into public.sessions (id, owner, profile_id, length_mode, tutor_mode, mistake_drill, focus_section, subjects)
    values (p_session_id, uid, p_profile_id, p_length_mode, p_tutor_mode, p_mistake_drill, p_focus_section,
            coalesce(p_subjects, '{}'))
    returning * into s;
    return jsonb_build_object('allowed', true, 'session_id', s.id, 'started_at', s.started_at);
end;
$$;

-- End of a training: the whole result in one call, stored in one transaction together
-- with the statistics and the streak. A session never begun (old history, or begun
-- offline) is created as imported. Repeating the call for a finished session is harmless.
--
-- p_session: {"id", "profile_id", "started_at", "finished_at", "length_mode", "tutor_mode",
--             "mistake_drill", "focus_section",
--             "subjects": [{"subject", "earned", "max_points", "projected_raw", "nmt_200", "is_full", "drills_done"}],
--             "answers":  [{"subject", "question_no", "task_id", "section", "qtype", "is_correct", "points",
--                           "max_points", "checked", "max_hint_level", "answered_at"}],
--             "hints":    [{"subject", "question_no", "task_id", "level", "opened_at"}]}
create or replace function public.submit_session(p_session jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    uid uuid := auth.uid();
    sid uuid := (p_session ->> 'id')::uuid;
    pid uuid := (p_session ->> 'profile_id')::uuid;
    s public.sessions;
    fin timestamptz;
    subj text;
    streak jsonb;
begin
    if uid is null then
        raise exception 'not signed in';
    end if;
    if not exists (select 1 from public.profiles where id = pid and owner = uid) then
        raise exception 'profile not found';
    end if;
    select * into s from public.sessions where id = sid for update;
    if found and s.owner <> uid then
        raise exception 'not allowed';
    end if;
    if found and s.status = 'finished' then
        return jsonb_build_object('ok', true, 'already', true);
    end if;
    if not found then
        insert into public.sessions (id, owner, profile_id, started_at, length_mode, tutor_mode, mistake_drill,
                                     focus_section, subjects, imported)
        values (sid, uid, pid, least(coalesce((p_session ->> 'started_at')::timestamptz, now()), now()),
                coalesce(p_session ->> 'length_mode', 'quick'), coalesce((p_session ->> 'tutor_mode')::boolean, true),
                coalesce((p_session ->> 'mistake_drill')::boolean, false), p_session ->> 'focus_section',
                array(select jsonb_array_elements(coalesce(p_session -> 'subjects', '[]')) ->> 'subject'), true)
        returning * into s;
    end if;
    -- The finish time comes from the device, kept between the server start and now.
    fin := least(greatest(coalesce((p_session ->> 'finished_at')::timestamptz, now()), s.started_at), now());
    update public.sessions set status = 'finished', finished_at = fin where id = sid;

    insert into public.session_subjects (session_id, owner, subject, earned, max_points, projected_raw, nmt_200,
                                         is_full, drills_done)
    select sid, uid, x.subject, x.earned, x.max_points, x.projected_raw, x.nmt_200, coalesce(x.is_full, false),
           coalesce(x.drills_done, 0)
    from jsonb_to_recordset(coalesce(p_session -> 'subjects', '[]')) as x(
        subject text, earned integer, max_points integer, projected_raw integer, nmt_200 integer,
        is_full boolean, drills_done integer)
    on conflict do nothing;

    insert into public.session_answers (session_id, owner, subject, question_no, task_id, section, qtype, is_correct,
                                        points, max_points, checked, max_hint_level, answered_at)
    select sid, uid, x.subject, x.question_no, x.task_id, x.section, x.qtype, x.is_correct, x.points, x.max_points,
           coalesce(x.checked, true), least(greatest(coalesce(x.max_hint_level, 0), 0), 10),
           least(greatest(coalesce(x.answered_at, fin), s.started_at), fin)
    from jsonb_to_recordset(coalesce(p_session -> 'answers', '[]')) as x(
        subject text, question_no integer, task_id text, section text, qtype text, is_correct boolean,
        points integer, max_points integer, checked boolean, max_hint_level integer, answered_at timestamptz)
    on conflict do nothing;

    insert into public.hint_events (session_id, owner, subject, question_no, task_id, level, opened_at)
    select sid, uid, x.subject, x.question_no, x.task_id, x.level,
           least(greatest(coalesce(x.opened_at, fin), s.started_at), fin)
    from jsonb_to_recordset(coalesce(p_session -> 'hints', '[]')) as x(
        subject text, question_no integer, task_id text, level integer, opened_at timestamptz)
    where x.level between 1 and 10;

    for subj in select distinct ss.subject from public.session_subjects ss where ss.session_id = sid loop
        perform public.recalc_subject_stats(pid, subj);
    end loop;
    streak := public.update_streak(pid, fin);
    return jsonb_build_object('ok', true, 'streak', streak);
end;
$$;

-- Account deletion (required by the App Store): the user and, by cascade, all their rows.
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    uid uuid := (select auth.uid());
begin
    if uid is null then
        raise exception 'not signed in';
    end if;
    delete from auth.users where id = uid;
end;
$$;

