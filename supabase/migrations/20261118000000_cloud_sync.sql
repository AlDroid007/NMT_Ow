-- NMT Tutor cloud database: profiles, training sessions with every answer and hint,
-- per-subject statistics, profile metadata (streaks, medals, ...) and the tables
-- that in-app purchases will use.
--
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste this file -> Run.
-- The script can be run again safely.
--
-- Access model (Row Level Security):
-- * a student (Supabase Auth user) sees only rows with owner = their user id;
-- * users listed in public.admins can read every row (future Vue 3 admin panel);
-- * the public (anon) key alone sees nothing;
-- * the app writes only its profile directly. Sessions, answers, hints, statistics,
--   metadata, purchases and credits are written by the security-definer functions
--   below (begin_session, submit_session, ...), so a student cannot fake them by
--   calling the REST API.
--
-- One cloud account = one student profile.

-- ===========================================================================
-- Helpers
-- ===========================================================================

create table if not exists public.admins (
    user_id uuid primary key references auth.users (id) on delete cascade,
    note text,
    created_at timestamptz not null default now()
);
alter table public.admins enable row level security;  -- no policies: dashboard only

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (select 1 from public.admins a where a.user_id = (select auth.uid()));
$$;

-- The server clock decides `updated_at` (sync cursor), so a wrong device clock does not matter.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

