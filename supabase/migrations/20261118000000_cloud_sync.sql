-- Free-form extra data of a profile.
-- * data        — written only by the server: streak, medals, counters (see submit_session);
-- * client_data — the app may write its own settings here.
create table if not exists public.profile_meta (
    profile_id uuid primary key references public.profiles (id) on delete cascade,
    owner uuid not null references auth.users (id) on delete cascade,
    data jsonb not null default '{}'::jsonb,
    client_data jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create or replace function public.create_profile_meta()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profile_meta (profile_id, owner) values (new.id, new.owner)
    on conflict (profile_id) do nothing;
    return new;
end;
$$;

drop trigger if exists profiles_meta on public.profiles;
create trigger profiles_meta after insert on public.profiles
    for each row execute function public.create_profile_meta();

-- ===========================================================================
-- Training sessions
-- ===========================================================================

create table if not exists public.sessions (
    id uuid primary key,                              -- generated by the app
    owner uuid not null references auth.users (id) on delete cascade,
    profile_id uuid not null references public.profiles (id) on delete cascade,
    status text not null default 'active' check (status in ('active', 'finished')),
    started_at timestamptz not null default now(),    -- server time (begin_session)
    finished_at timestamptz,
    length_mode text not null check (length_mode in ('quick', 'medium', 'full', 'focus')),
    tutor_mode boolean not null default true,          -- hints allowed (false = exam mode)
    mistake_drill boolean not null default false,      -- «робота над помилками»
    focus_section text,                                 -- one-topic training («Потренувати»)
    subjects text[] not null default '{}',
    imported boolean not null default false,            -- uploaded later without begin_session (old history)
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (finished_at is null or finished_at >= started_at)
);

-- Result per subject of a finished session.
create table if not exists public.session_subjects (
    session_id uuid not null references public.sessions (id) on delete cascade,
    owner uuid not null references auth.users (id) on delete cascade,
    subject text not null,
    earned integer not null,            -- points scored
    max_points integer not null,        -- points possible in this session
    projected_raw integer,              -- scaled to the official test size
    nmt_200 integer check (nmt_200 between 100 and 200),  -- null = below the pass threshold
    is_full boolean not null default false,               -- full official format (not a projection)
    drills_done integer not null default 0,               -- similar examples practised with the tutor
    primary key (session_id, subject)
);

-- Every task of a session the student answered.
create table if not exists public.session_answers (
    session_id uuid not null references public.sessions (id) on delete cascade,
    owner uuid not null references auth.users (id) on delete cascade,
    subject text not null,
    question_no integer not null,       -- position in the subject block, from 0
    task_id text,                       -- bank task id, or "gen:<generator>" for generated tasks
    section text,                       -- topic of the task
    qtype text,                         -- single / matching / short
    is_correct boolean not null,
    points integer not null,
    max_points integer not null,
    checked boolean not null default true,       -- false: left with the answer chosen but not checked
    max_hint_level smallint not null default 0,  -- deepest hint opened before answering (0-10)
    answered_at timestamptz not null,
    primary key (session_id, subject, question_no)
);

-- Every hint level the student opened.
create table if not exists public.hint_events (
    id bigint generated always as identity primary key,
    session_id uuid not null references public.sessions (id) on delete cascade,
    owner uuid not null references auth.users (id) on delete cascade,
    subject text not null,
    question_no integer not null,
    task_id text,
    level smallint not null check (level between 1 and 10),
    opened_at timestamptz not null
);

-- Running totals per profile and subject, maintained by the server (recalc_subject_stats).
create table if not exists public.profile_subject_stats (
    profile_id uuid not null references public.profiles (id) on delete cascade,
    subject text not null,
    owner uuid not null references auth.users (id) on delete cascade,
    sessions_count integer not null default 0,     -- scored sessions (without mistake drills)
    best_nmt integer,
    last_nmt integer,
    avg_nmt numeric(5, 1),
    level_nmt numeric(5, 1),                       -- average of the last 3 scored sessions
    answers_total integer not null default 0,
    answers_correct integer not null default 0,
    hints_opened integer not null default 0,
    last_session_at timestamptz,
    updated_at timestamptz not null default now(),
    primary key (profile_id, subject)
);

create index if not exists sessions_owner_updated on public.sessions (owner, updated_at);
create index if not exists sessions_profile_started on public.sessions (profile_id, started_at);
create index if not exists session_subjects_subject on public.session_subjects (subject);
create index if not exists session_answers_section on public.session_answers (subject, section);
create index if not exists session_answers_task on public.session_answers (task_id);
create index if not exists hint_events_session on public.hint_events (session_id, subject, question_no);

