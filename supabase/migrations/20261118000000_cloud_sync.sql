-- ===========================================================================
-- Views for the admin panel (security_invoker: a student sees only their own rows)
-- ===========================================================================

-- One row per student: name, how much and how well they train.
create or replace view public.admin_students
with (security_invoker = true)
as
select
    p.id as profile_id,
    p.owner,
    p.name,
    p.exam_date,
    p.created_at,
    (select count(*) from public.sessions s where s.profile_id = p.id and s.status = 'finished') as sessions_total,
    (select max(s.finished_at) from public.sessions s where s.profile_id = p.id) as last_session_at,
    (select round(avg(st.level_nmt), 1) from public.profile_subject_stats st where st.profile_id = p.id) as avg_level_nmt,
    (m.data -> 'streak' ->> 'current')::integer as streak_current,
    (m.data -> 'streak' ->> 'best')::integer as streak_best
from public.profiles p
left join public.profile_meta m on m.profile_id = p.id;

-- Topics: how often tasks of each section are answered wrong and how many hints they need.
create or replace view public.admin_sections
with (security_invoker = true)
as
select
    a.subject,
    a.section,
    count(*) as answers,
    count(*) filter (where not a.is_correct) as wrong,
    round(100.0 * count(*) filter (where a.is_correct) / nullif(count(*), 0), 1) as correct_pct,
    round(avg(a.max_hint_level), 2) as avg_hint_level,
    count(*) filter (where a.max_hint_level > 0) as answered_with_hints
from public.session_answers a
group by a.subject, a.section;

-- Hints: at which level students stop (for each subject and level).
create or replace view public.admin_hint_levels
with (security_invoker = true)
as
select
    a.subject,
    a.max_hint_level,
    count(*) as answers,
    round(100.0 * count(*) filter (where a.is_correct) / nullif(count(*), 0), 1) as correct_pct
from public.session_answers a
group by a.subject, a.max_hint_level;

grant select on public.admin_students, public.admin_sections, public.admin_hint_levels to authenticated;
revoke all on public.admin_students, public.admin_sections, public.admin_hint_levels from anon;
