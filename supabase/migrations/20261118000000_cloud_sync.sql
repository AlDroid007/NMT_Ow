-- Recomputes one row of profile_subject_stats from the raw tables (never drifts).
create or replace function public.recalc_subject_stats(p_profile_id uuid, p_subject text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_owner uuid;
begin
    select owner into v_owner from public.profiles where id = p_profile_id;
    if v_owner is null then
        return;
    end if;
    insert into public.profile_subject_stats as st (
        profile_id, subject, owner, sessions_count, best_nmt, last_nmt, avg_nmt, level_nmt,
        answers_total, answers_correct, hints_opened, last_session_at, updated_at)
    select
        p_profile_id, p_subject, v_owner,
        coalesce(sc.n, 0), sc.best, sc.last, sc.avg, sc.lvl,
        coalesce(an.total, 0), coalesce(an.correct, 0), coalesce(hi.n, 0), sc.last_at, now()
    from (
        select count(*) as n,
               max(x.nmt_200) as best,
               (array_agg(x.nmt_200 order by x.started_at desc))[1] as last,
               round(avg(x.nmt_200), 1) as avg,
               round(avg(x.nmt_200) filter (where x.rn <= 3), 1) as lvl,
               max(x.started_at) as last_at
        from (
            select ss.nmt_200, s.started_at, row_number() over (order by s.started_at desc) as rn
            from public.session_subjects ss
            join public.sessions s on s.id = ss.session_id
            where s.profile_id = p_profile_id and ss.subject = p_subject
              and s.status = 'finished' and not s.mistake_drill
        ) x
    ) sc,
    (
        select count(*) as total, count(*) filter (where a.is_correct) as correct
        from public.session_answers a
        join public.sessions s on s.id = a.session_id
        where s.profile_id = p_profile_id and a.subject = p_subject
    ) an,
    (
        select count(*) as n
        from public.hint_events h
        join public.sessions s on s.id = h.session_id
        where s.profile_id = p_profile_id and h.subject = p_subject
    ) hi
    on conflict (profile_id, subject) do update set
        sessions_count = excluded.sessions_count, best_nmt = excluded.best_nmt, last_nmt = excluded.last_nmt,
        avg_nmt = excluded.avg_nmt, level_nmt = excluded.level_nmt, answers_total = excluded.answers_total,
        answers_correct = excluded.answers_correct, hints_opened = excluded.hints_opened,
        last_session_at = excluded.last_session_at, updated_at = now();
end;
$$;

-- Full recalculation (after the formula changes). Admins: any profile or all; students: their own.
create or replace function public.recalc_stats(p_profile_id uuid default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    r record;
    n integer := 0;
begin
    if not public.is_admin() then
        if p_profile_id is null or not exists (
            select 1 from public.profiles where id = p_profile_id and owner = auth.uid()) then
            raise exception 'not allowed';
        end if;
    end if;
    for r in
        select distinct s.profile_id, ss.subject
        from public.session_subjects ss join public.sessions s on s.id = ss.session_id
        where p_profile_id is null or s.profile_id = p_profile_id
    loop
        perform public.recalc_subject_stats(r.profile_id, r.subject);
        n := n + 1;
    end loop;
    return n;
end;
$$;

-- Streak of consecutive training days (calendar day in app_settings.day_timezone).
create or replace function public.update_streak(p_profile_id uuid, p_at timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    tz text := coalesce(public.setting('day_timezone') #>> '{}', 'Europe/Kyiv');
    today date := (p_at at time zone tz)::date;
    cur jsonb;
    last_day date;
    current_n integer;
    best_n integer;
begin
    select data -> 'streak' into cur from public.profile_meta where profile_id = p_profile_id;
    last_day := (cur ->> 'last_day')::date;
    current_n := coalesce((cur ->> 'current')::integer, 0);
    best_n := coalesce((cur ->> 'best')::integer, 0);
    if last_day is null or today > last_day + 1 then
        current_n := 1;
    elsif today = last_day + 1 then
        current_n := current_n + 1;
    elsif today < last_day then
        return cur;  -- an old session uploaded late does not move the streak
    end if;
    best_n := greatest(best_n, current_n);
    cur := jsonb_build_object('current', current_n, 'best', best_n, 'last_day', greatest(today, last_day));
    update public.profile_meta set data = jsonb_set(data, '{streak}', cur) where profile_id = p_profile_id;
    return cur;
end;
$$;

